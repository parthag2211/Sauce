import { readFile,writeFile,mkdir } from 'node:fs/promises';
import { resolve,dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const names=['index.html','app.js','data.js','style.css','logo.svg','working.html','working.js','working.css'];
const assets={};for(const name of names)assets['/'+name]=await readFile(resolve(root,'public',name),'utf8');
const samples=await readFile(resolve(root,'backend/samples.mjs'),'utf8');
const backend=(await readFile(resolve(root,'backend/live-demo.mjs'),'utf8')).replace("import { SAMPLES, CRITERIA } from './samples.mjs';",'');
const source=`// Generated by scripts/build-worker.mjs from the reviewed GitHub source. Contains no secrets.\n${samples}\n${backend}\nconst ASSETS=${JSON.stringify(assets)};\n
const TYPES={html:'text/html; charset=utf-8',js:'text/javascript; charset=utf-8',css:'text/css; charset=utf-8',svg:'image/svg+xml'};
export default {async fetch(request,env){
 const apiResponse=await handleDemoAPI(request,env);if(apiResponse)return apiResponse;
 if(!['GET','HEAD'].includes(request.method))return new Response('Method not allowed',{status:405});
 let pathname=new URL(request.url).pathname;
 if(pathname==='/')pathname='/index.html';if(pathname==='/working')pathname='/working.html';
 const content=ASSETS[pathname];if(!content)return new Response('Not found',{status:404});
 const type=TYPES[pathname.split('.').pop()];
 return new Response(request.method==='HEAD'?null:content,{headers:{'Content-Type':type,'Cache-Control':'no-cache','X-Content-Type-Options':'nosniff','Referrer-Policy':'strict-origin-when-cross-origin','Content-Security-Policy':\"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'\"}});
}};\n`;
await mkdir(resolve(root,'worker'),{recursive:true});await writeFile(resolve(root,'worker/index.js'),source);
console.log('Worker assembled from public assets and backend modules. No environment files included.');
